"""Build gamedata.js (item, accolade and damage source names) and assets/items/*.webp from Deadlock's own files.

Input: a folder holding the files from raw/ranks_items_raw.zip on the assets-portraits-raw branch:
  scripts/abilities.vdata_c, scripts/accolades.vdata_c, scripts/heroes.vdata_c,
  resource/localization/citadel_gc_mod_names/citadel_gc_mod_names_english.txt,
  resource/localization/citadel_heroes/citadel_heroes_english.txt,
  resource/localization/citadel_vdata/accolades/accolades_english.txt,
  panorama/images/items/**/*_psd.png (decoded with s2decode.py).
Item ids in match data are MurmurHash2 (seed 0x31415926) of the lower-case class name.
Usage: python3 tools/build_gamedata.py <folder>
"""
import json, os, re, sys
from PIL import Image
sys.path.insert(0, os.path.dirname(__file__))
from kv3 import read

SEED = 0x31415926


def murmur2(key, seed=SEED):
    m, n = 0x5bd1e995, len(key)
    h = (seed ^ n) & 0xffffffff
    i = 0
    while n - i >= 4:
        k = int.from_bytes(key[i:i + 4], 'little')
        k = (k * m) & 0xffffffff; k ^= k >> 24; k = (k * m) & 0xffffffff
        h = ((h * m) & 0xffffffff) ^ k
        i += 4
    r = n - i
    if r == 3: h ^= key[i + 2] << 16
    if r >= 2: h ^= key[i + 1] << 8
    if r >= 1: h ^= key[i]; h = (h * m) & 0xffffffff
    h ^= h >> 13; h = (h * m) & 0xffffffff; h ^= h >> 15
    return h


def loc(path):
    out = {}
    for line in open(path, encoding='utf-8-sig'):
        m = re.match(r'\s*"([^"]+)"\s+"((?:[^"\\]|\\.)*)"', line)
        if m: out[m.group(1)] = m.group(2).replace('\\"', '"')
    return out


def plural(s, form):
    # {stat_value, plural, one{kill} other{kills}} -> the chosen form
    return re.sub(r'\{stat_value, plural, one\{([^}]*)\} other\{([^}]*)\}\}', lambda m: m.group(1 if form == 'one' else 2), s)


def main(src):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    L = os.path.join(src, 'resource', 'localization')
    mods = {k.lower(): v for k, v in loc(os.path.join(L, 'citadel_gc_mod_names', 'citadel_gc_mod_names_english.txt')).items()}
    heroes = {k.lower(): v for k, v in loc(os.path.join(L, 'citadel_heroes', 'citadel_heroes_english.txt')).items()}
    accl = loc(os.path.join(L, 'citadel_vdata', 'accolades', 'accolades_english.txt'))

    abil, chk = read(os.path.join(src, 'scripts', 'abilities.vdata_c'))
    assert not chk['types_left'] and not any(chk['main'].values()), chk
    slot = {'EItemSlotType_WeaponMod': 'w', 'EItemSlotType_Armor': 'v', 'EItemSlotType_Tech': 's'}
    items, icons = {}, {}
    for k, v in abil.items():
        if not isinstance(v, dict) or v.get('m_eAbilityType') != 'EAbilityType_Item': continue
        name = mods.get(k.lower())
        s = slot.get(v.get('m_eItemSlotType'))
        icon = (v.get('m_strShopIconLarge') or '').replace('file://{images}/', '')
        if not name or not s or not icon: continue
        tier = int(re.sub(r'\D', '', v.get('m_iItemTier') or '') or 0)
        base = os.path.basename(icon).replace('.psd', '')
        items[murmur2(k.lower().encode())] = [name, s, tier, base]
        icons[base] = os.path.join(src, 'panorama', 'images', icon.replace('.psd', '_psd.png'))

    # Damage source names (damage_matrix source_name): hero abilities, weapons and items.
    srcs = {}
    for k, v in abil.items():
        if not isinstance(v, dict): continue
        n = heroes.get(k.lower()) or mods.get(k.lower())
        if n: srcs[k] = n

    acc, chk = read(os.path.join(src, 'scripts', 'accolades.vdata_c'))
    assert not chk['types_left'], chk
    accolades = {}
    for k, v in acc.items():
        if not isinstance(v, dict) or 'm_unAccoladeID' not in v: continue
        fn = accl.get(v['m_sFlavorName'].lstrip('#'), k)
        d = re.sub(r'<[^>]+>', '', accl.get(v['m_sDescription'].lstrip('#'), ''))
        d = d.replace('{g:citadel_thousands:stat_value}', '{v}')
        accolades[v['m_unAccoladeID']] = [fn, plural(d, 'one'), plural(d, 'other')]

    # Base max health per hero_id (heroes.vdata m_mapStartingStats), so the Power graphs can start at 0:00.
    hero_v, chk = read(os.path.join(src, 'scripts', 'heroes.vdata_c'))
    base_hp = hero_v['hero_base']['m_mapStartingStats']['EMaxHealth']
    hp = {}
    for k, v in hero_v.items():
        if isinstance(v, dict) and k.startswith('hero_') and v.get('m_HeroID'):
            hp[v['m_HeroID']] = round((v.get('m_mapStartingStats') or {}).get('EMaxHealth', base_hp))

    out = os.path.join(root, 'assets', 'items')
    os.makedirs(out, exist_ok=True)
    for base, p in icons.items():
        Image.open(p).convert('RGBA').resize((64, 64), Image.LANCZOS).save(os.path.join(out, base + '.webp'), 'WEBP', quality=88, method=6)

    js = ('"use strict";\n// Generated by tools/build_gamedata.py from Deadlock\'s own files. Do not edit by hand.\n'
          '// ITEMS: item_id -> [name, slot (w weapon, v vitality, s spirit), tier, icon in assets/items/]\n'
          'window.ITEMS = ' + json.dumps({str(k): v for k, v in sorted(items.items())}, separators=(',', ':')) + ';\n'
          '// ACCOLADES: accolade_id -> [name, text for 1, text for many] ({v} is the value)\n'
          'window.ACCOLADES = ' + json.dumps({str(k): v for k, v in sorted(accolades.items())}, separators=(',', ':')) + ';\n'
          '// SOURCE_NAMES: damage_matrix source_name -> in-game name\n'
          'window.SOURCE_NAMES = ' + json.dumps(dict(sorted(srcs.items())), separators=(',', ':')) + ';\n'
          '// HERO_HP: hero_id -> base max health at level 1\n'
          'window.HERO_HP = ' + json.dumps({str(k): v for k, v in sorted(hp.items())}, separators=(',', ':')) + ';\n')
    open(os.path.join(root, 'gamedata.js'), 'w').write(js)
    print(len(items), 'items,', len(icons), 'icons,', len(accolades), 'accolades,', len(srcs), 'source names')


if __name__ == '__main__':
    main(sys.argv[1])
