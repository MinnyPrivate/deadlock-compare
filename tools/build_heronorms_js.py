"""Builds heronorms.js from hero_table.json, snap_norms.json and length_norms.json.
Usage: python3 tools/build_heronorms_js.py tools/data/hero_table.json tools/data/snap_norms.json [heronorms.js] [length_norms.json]
"""
import json
import sys
from pathlib import Path

table = json.loads(Path(sys.argv[1]).read_text(encoding="utf8"))
norms = json.loads(Path(sys.argv[2]).read_text(encoding="utf8"))
out = Path(sys.argv[3]) if len(sys.argv) > 3 else Path("heronorms.js")
length_path = Path(sys.argv[4]) if len(sys.argv) > 4 else Path(__file__).parent / "data/length_norms.json"
length_norms = json.loads(length_path.read_text(encoding="utf8"))
with out.open("w", encoding="utf8", newline="\n") as f:
    f.write("// Generated by tools/build_heronorms_js.py. Do not edit by hand.\n")
    f.write("window.HERO_TABLE = " + json.dumps(table, separators=(",", ":")) + ";\n")
    f.write("window.LENGTH_NORMS = " + json.dumps(length_norms, separators=(",", ":")) + ";\n")
    f.write("window.SNAP_NORMS = " + json.dumps(norms, separators=(",", ":")) + ";\n")
