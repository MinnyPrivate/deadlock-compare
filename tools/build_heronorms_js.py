"""Builds heronorms.js from hero_table.json and snap_norms.json.
Usage: python3 tools/build_heronorms_js.py tools/data/hero_table.json tools/data/snap_norms.json [heronorms.js]
"""
import json, sys

table = json.load(open(sys.argv[1]))
norms = json.load(open(sys.argv[2]))
out = sys.argv[3] if len(sys.argv) > 3 else "heronorms.js"
with open(out, "w") as f:
    f.write("// Generated by tools/build_heronorms_js.py. Do not edit by hand.\n")
    f.write("window.HERO_TABLE = " + json.dumps(table, separators=(",", ":")) + ";\n")
    f.write("window.SNAP_NORMS = " + json.dumps(norms, separators=(",", ":")) + ";\n")
