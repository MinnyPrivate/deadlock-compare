// Builds card/art.js from the SVG sources in card/src.
// Run: node tools/build_card_art.mjs
// Sources: hero_<id>.svg (traced with tools/trace_hero_silhouette.py from the game's
// hero card render alpha; first path = silhouette, second = eyes), suit_<name>.svg
// (the game's own flat icons), logo.svg (our obol mark, swappable).
import fs from 'node:fs';
import path from 'node:path';
const dir = path.resolve('card/src');
const out = { heroes: {}, suits: {}, logo: null, logoPlain: null };
const vb = s => (s.match(/viewBox="([^"]+)"/) || [])[1];
const paths = s => [...s.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1]);
for (const f of fs.readdirSync(dir).sort()) {
  const s = fs.readFileSync(path.join(dir, f), 'utf8');
  let m;
  if ((m = f.match(/^hero_(\d+)\.svg$/))) {
    const [body, eyes = ''] = paths(s);
    const fr = (s.match(/data-frame="([^"]+)"/) || [])[1];
    out.heroes[m[1]] = { viewBox: vb(s), body, eyes, frame: fr ? fr.split(' ').map(Number) : null };
  } else if ((m = f.match(/^suit_(\w+)\.svg$/))) {
    out.suits[m[1]] = { viewBox: vb(s), d: paths(s).join(' ') };
  } else if (f === 'logo.svg' || f === 'logo_plain.svg') {
    const inner = s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>[^<]*<\/title>/, '').trim();
    out[f === 'logo.svg' ? 'logo' : 'logoPlain'] = { viewBox: vb(s), inner };
  }
}
const js = `// Generated by tools/build_card_art.mjs. Do not edit by hand.\nwindow.PM_CARD_ART = ${JSON.stringify(out)};\n`;
fs.writeFileSync('card/art.js', js);
console.log('card/art.js', js.length, 'bytes', Object.keys(out.heroes), Object.keys(out.suits), !!out.logo);
